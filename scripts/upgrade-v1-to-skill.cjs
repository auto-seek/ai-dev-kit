#!/usr/bin/env node
// Convert generated ai-dev-kit v1 instruction files to v2 skill-first pointers.

const fs = require("node:fs");
const path = require("node:path");

const args = process.argv.slice(2);

function usage() {
  console.log(`Usage: node scripts/upgrade-v1-to-skill.cjs <project-path> [--harness codex|claude|both]

Rewrites generated V1 AGENTS.md/CLAUDE.md into thin V2 skill-first pointers
while preserving project-specific overview, commands, directories, and extension
sections. Existing files are backed up before rewrite.`);
}

let projectPath = "";
let harness = "both";

for (let index = 0; index < args.length; index += 1) {
  const arg = args[index];
  if (arg === "--help") {
    usage();
    process.exit(0);
  } else if (arg === "--harness") {
    harness = args[++index] ?? "both";
  } else if (!projectPath) {
    projectPath = arg;
  } else {
    console.error(`Unknown argument: ${arg}`);
    usage();
    process.exit(1);
  }
}

if (!projectPath) {
  usage();
  process.exit(1);
}

if (!["codex", "claude", "both"].includes(harness)) {
  console.error("--harness must be codex, claude, or both");
  process.exit(1);
}

const root = path.resolve(projectPath);
const stamp = new Date().toISOString().replace(/[-:T.Z]/g, "").slice(0, 14);

function isGeneratedV1(text) {
  return text.includes("Auto-generated by [ai-dev-kit]") || text.includes("MANDATORY — VIOLATION = TASK FAILURE");
}

function dropV1Blocks(text) {
  const blocks = text.split(/\n---\n/g);
  const kept = [];

  for (const block of blocks) {
    if (block.includes("## Programming Principles")) continue;
    if (block.includes("## Code Review Checklist")) continue;
    kept.push(block.trim());
  }

  return kept.filter(Boolean);
}

function rewriteInstruction(relativePath, label) {
  const file = path.join(root, relativePath);
  if (!fs.existsSync(file)) return false;

  const original = fs.readFileSync(file, "utf8");
  if (!isGeneratedV1(original)) {
    console.log(`skip ${relativePath}: not recognized as generated V1`);
    return false;
  }

  const backup = `${file}.v1.bak.${stamp}`;
  fs.copyFileSync(file, backup);

  const kept = dropV1Blocks(original);
  if (kept[0]) {
    kept[0] = kept[0].replace(
      /^> Auto-generated by \[ai-dev-kit\].*$/m,
      "> Managed by ai-dev-kit v2 skill-first workflow."
    );
  }
  const body = [];
  body.push(kept[0] ?? `# Project Instructions`);
  body.push(``);
  body.push(`---`);
  body.push(``);
  body.push(`## AI Dev Kit Skill-First Workflow`);
  body.push(``);
  body.push(`<!-- AI_DEV_KIT_SKILL_FIRST -->`);
  body.push(`This project uses ai-dev-kit v2. Use the local skill first:`);
  body.push(``);
  body.push("`.ai-dev-kit/skills/ai-dev-kit/SKILL.md`");
  body.push(``);
  body.push(`Project profile:`);
  body.push(``);
  body.push("`.ai-dev-kit/profile.yml`");
  body.push(``);
  body.push(`Loop work must reserve the feature in \`docs/development/feature-ledger.md\` before creating a worktree from \`dev\`.`);
  body.push(``);
  body.push(`Tests are not trusted as evidence until a test-review pass validates the test contract and assertions.`);
  body.push(``);
  body.push(`Keep documents synchronized with development reality; stale brainstorming/planning docs must be marked superseded or archived.`);

  for (const block of kept.slice(1)) {
    body.push(``);
    body.push(`---`);
    body.push(``);
    body.push(block);
  }

  fs.writeFileSync(file, `${body.join("\n").trimEnd()}\n`);
  console.log(`rewrote ${relativePath} for ${label}; backup=${path.relative(root, backup)}`);
  return true;
}

function rewritePreflight(relativePath) {
  const file = path.join(root, relativePath);
  if (!fs.existsSync(file)) return false;

  const original = fs.readFileSync(file, "utf8");
  const legacyDetectPrefix = ["det", "ect-"].join("");
  const legacyGateLabel = ["Quality", " Gate"].join("");
  if (!original.includes(legacyDetectPrefix) && !original.includes(legacyGateLabel)) {
    return false;
  }

  const backup = `${file}.v1.bak.${stamp}`;
  fs.copyFileSync(file, backup);
  fs.writeFileSync(file, `# AI Dev Kit v2 Preflight

Run this before merging a feature branch back to dev.

## 1. Skill-First Gate

\`\`\`bash
bash <ai-dev-kit-path>/scripts/skill-first-gate.sh --phase preflight --project .
\`\`\`

## 2. Project Commands

Read \`.ai-dev-kit/profile.yml\` and run the available project commands:

- build
- lint
- typecheck
- test
- e2e, when the change affects user-visible behavior and an E2E path exists

## 3. Agent Review

Use the local skill prompts:

- \`.ai-dev-kit/skills/ai-dev-kit/references/test-review.md\`
- \`.ai-dev-kit/skills/ai-dev-kit/references/document-discipline.md\`
- \`.ai-dev-kit/skills/ai-dev-kit/references/review-agents.md\`
- \`.ai-dev-kit/skills/ai-dev-kit/references/agent-prompts.md\`

Required reviewers depend on the change:

- changed tests -> test-review agent
- changed docs or behavior that docs describe -> doc-curator/fact reviewer
- public API, shared utility, module boundary, or new abstraction -> architecture reviewer
- merge to dev -> merge guardian

## 4. Verdict

Return READY only when:

- the feature-ledger entry is ready for review;
- blocking findings are closed;
- tests used as evidence passed test-review;
- docs match implemented behavior;
- no placeholder, mock, or unfinished production path is being merged.
`);
  console.log(`rewrote ${relativePath}; backup=${path.relative(root, backup)}`);
  return true;
}

let changed = false;
if (harness === "codex" || harness === "both") {
  changed = rewriteInstruction("AGENTS.md", "Codex") || changed;
  changed = rewritePreflight(".codex/commands/preflight.md") || changed;
}
if (harness === "claude" || harness === "both") {
  changed = rewriteInstruction("CLAUDE.md", "Claude") || changed;
  changed = rewritePreflight(".claude/commands/preflight.md") || changed;
}

const v1Config = path.join(root, ".ai-dev-kit/config");
if (fs.existsSync(v1Config)) {
  const backup = `${v1Config}.v1.bak.${stamp}`;
  fs.renameSync(v1Config, backup);
  console.log(`retired .ai-dev-kit/config to ${path.relative(root, backup)}`);
  changed = true;
}

if (!changed) {
  console.log("No V1 instruction/config files changed.");
}
